/// One of the family's models: carried or held, never on the floor (`ground` off).
// (`tolerance`: a thing a centimetre across measures to the millimetre, not the 2 %.)
fn i(
    id: &'static str,
    build: Build,
    size: (f64, f64, f64),
    key: &'static str,
    centre: (f64, f64),
    code: bool,
    tolerance: f64,
) -> Model {
    let model = Model::new(id, build, size)
        .key(key)
        .centre(centre.0, centre.1)
        .ground(false)
        .tolerance(tolerance);
    if code { model.code() } else { model }
}

